export const getColorForValueSign = (
  value: number | string | null | undefined,
): string | null => {
  if (value === null || value === undefined) {
    return null
  }

  const numericValue = typeof value === "string" ? parseInt(value, 10) : value
  return numericValue < 0 ? red[800] : null
}
